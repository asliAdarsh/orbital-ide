#!/usr/bin/env python3
"""Freeze the Orbital backend as the Tauri sidecar binary.

    python backend/build_sidecar.py

Runs PyInstaller from the repository virtualenv against ``backend/orbital-backend.spec`` and copies
the artefact to ``src-tauri/binaries/orbital-backend-<target-triple>[.exe]``, the name Tauri's
``bundle.externalBin`` entry resolves for the host platform. PyInstaller cannot cross-compile, so
the triple is always the host's.
"""

from __future__ import annotations

import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent
REPO_ROOT = BACKEND_DIR.parent
SPEC_FILE = BACKEND_DIR / "orbital-backend.spec"
ENTRY_FILE = BACKEND_DIR / "build" / "orbital_sidecar_entry.py"
DIST_DIR = BACKEND_DIR / "dist"
WORK_DIR = BACKEND_DIR / "build" / "pyinstaller"
BINARIES_DIR = REPO_ROOT / "src-tauri" / "binaries"
ARTEFACT_NAME = "orbital-backend"

ENTRY_SOURCE = '''"""Generated by backend/build_sidecar.py - frozen entry point for the sidecar."""

from orbital_backend.__main__ import main

if __name__ == "__main__":
    main()
'''

ARCHITECTURES = {
    "amd64": "x86_64",
    "x86_64": "x86_64",
    "arm64": "aarch64",
    "aarch64": "aarch64",
    "x86": "i686",
    "i386": "i686",
    "i686": "i686",
}


def host_target_triple() -> str:
    """Rust target triple for this machine, matching Tauri's sidecar naming convention."""
    machine = platform.machine().lower()
    architecture = ARCHITECTURES.get(machine)
    if architecture is None:
        raise SystemExit(f"unsupported host architecture for sidecar naming: {machine}")
    if sys.platform == "win32":
        return f"{architecture}-pc-windows-msvc"
    if sys.platform == "darwin":
        return f"{architecture}-apple-darwin"
    return f"{architecture}-unknown-linux-gnu"


def interpreter() -> Path:
    """The repository virtualenv, which is where the backend dependencies live."""
    venv = REPO_ROOT / ".venv" / ("Scripts" if os.name == "nt" else "bin")
    executable = venv / ("python.exe" if os.name == "nt" else "python")
    return executable if executable.is_file() else Path(sys.executable)


def require_pyinstaller(python: Path) -> None:
    probe = subprocess.run(
        [str(python), "-c", "import PyInstaller"],
        capture_output=True,
        text=True,
    )
    if probe.returncode != 0:
        raise SystemExit(
            "PyInstaller is not available to the backend interpreter.\n"
            f"Install it with: {python} -m pip install pyinstaller"
        )


def write_entry_script() -> None:
    ENTRY_FILE.parent.mkdir(parents=True, exist_ok=True)
    ENTRY_FILE.write_text(ENTRY_SOURCE, encoding="utf-8")


def run_pyinstaller(python: Path) -> Path:
    command = [
        str(python),
        "-m",
        "PyInstaller",
        str(SPEC_FILE),
        "--noconfirm",
        "--distpath",
        str(DIST_DIR),
        "--workpath",
        str(WORK_DIR),
    ]
    print("running: " + " ".join(command))
    completed = subprocess.run(command, cwd=BACKEND_DIR)
    if completed.returncode != 0:
        raise SystemExit(f"PyInstaller exited with code {completed.returncode}")

    artefact = DIST_DIR / (f"{ARTEFACT_NAME}.exe" if os.name == "nt" else ARTEFACT_NAME)
    if not artefact.is_file():
        raise SystemExit(f"PyInstaller produced no artefact at {artefact}")
    return artefact


def install(artefact: Path, triple: str) -> Path:
    BINARIES_DIR.mkdir(parents=True, exist_ok=True)
    suffix = ".exe" if os.name == "nt" else ""
    destination = BINARIES_DIR / f"{ARTEFACT_NAME}-{triple}{suffix}"
    shutil.copy2(artefact, destination)
    return destination


def main() -> None:
    python = interpreter()
    triple = host_target_triple()
    require_pyinstaller(python)
    write_entry_script()
    destination = install(run_pyinstaller(python), triple)
    print(f"sidecar installed for {triple}: {destination} ({destination.stat().st_size} bytes)")
    print("tauri.conf.json bundle.externalBin resolves this through 'binaries/orbital-backend'")


if __name__ == "__main__":
    main()
